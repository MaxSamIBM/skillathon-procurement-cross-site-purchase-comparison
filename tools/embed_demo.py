#!/usr/bin/env python3
"""Embed the synthetic example files into the skill script (maintainers only, not part of the skill).

Run from anywhere:  python3 tools/embed_demo.py
It rewrites the block between '# BEGIN DEMO DATA' and '# END DEMO DATA' in
skills/cross-site-purchase-comparison/scripts/generate_cross_site_purchase_comparison.py
from skills/cross-site-purchase-comparison/examples/synthetic/.
"""
import os
import pprint

HERE = os.path.dirname(os.path.abspath(__file__))
SKILL = os.path.join(HERE, "..", "skills", "cross-site-purchase-comparison")
EX = os.path.join(SKILL, "examples", "synthetic")
SCRIPT = os.path.join(SKILL, "scripts", "generate_cross_site_purchase_comparison.py")
BEGIN, END = "# BEGIN DEMO DATA\n", "# END DEMO DATA\n"


def text(*parts):
    with open(os.path.join(EX, *parts), "rb") as f:
        return f.read().decode("utf-8")


def main():
    common = {"scope_csv.json": text("scope_csv.json"), "rules.json": text("rules.json")}
    plants = sorted(n for n in os.listdir(os.path.join(EX, "inputs_csv")) if n.endswith(".csv"))
    for name in plants:
        common["inputs_csv/" + name] = text("inputs_csv", name)
    stages = {
        "0_start": text("decisions_0_start.json"),
        "1_scope_confirmed": text("decisions_1_scope_confirmed.json"),
        "2_signed_off": text("decisions_2_signed_off.json"),
    }
    block = (BEGIN
             + "# Generated by tools/embed_demo.py from examples/synthetic/. Synthetic data only; edit the examples, then re-run the tool.\n"
             + "DEMO_COMMON = " + pprint.pformat(common, width=110, sort_dicts=True) + "\n"
             + "DEMO_DECISIONS = " + pprint.pformat(stages, width=110, sort_dicts=True) + "\n"
             + END)
    with open(SCRIPT, encoding="utf-8") as f:
        source = f.read()
    start, stop = source.index(BEGIN), source.index(END) + len(END)
    with open(SCRIPT, "w", encoding="utf-8") as f:
        f.write(source[:start] + block + source[stop:])
    print(f"embedded {len(common)} files + {len(stages)} decision stages ({len(block)} chars)")


if __name__ == "__main__":
    main()
